//! IMG-001 (forjar#756): what an image resource's own `packages` / `command`
//! mean for the build, and the machine-readable build manifest.
//!
//! Split from `build_image.rs` to stay under the 500-line limit.

use crate::core::types::{ImageBuildPlan, LayerStrategy, Resource, ResourceType};

/// True when the plan declares `packages` or a build `command`. Those can only
/// be honoured by RUNNING them against the base image, so the build must go
/// through the container path; assembling files alone would silently drop them.
pub(crate) fn plan_needs_execution(plan: &ImageBuildPlan) -> bool {
    plan.layers.iter().any(|l| {
        matches!(
            l,
            LayerStrategy::Packages { .. } | LayerStrategy::Build { .. }
        )
    })
}

/// Scripts that realise the image resource's own `packages` (tier 0) then its
/// build `command` (tier 1), in that order. Generated by the same codegen every
/// other resource goes through; nothing is hand-assembled here.
pub(crate) fn image_build_scripts(
    plan: &ImageBuildPlan,
    res: &Resource,
) -> Result<Vec<String>, String> {
    let mut scripts = Vec::new();
    for layer in &plan.layers {
        match layer {
            LayerStrategy::Packages { names } => {
                let pkg = Resource {
                    resource_type: ResourceType::Package,
                    provider: Some(res.provider.clone().unwrap_or_else(|| "apt".into())),
                    packages: names.clone(),
                    ..Resource::default()
                };
                scripts.push(crate::core::codegen::apply_script(&pkg)?);
            }
            LayerStrategy::Build { command, .. } => {
                let task = Resource {
                    resource_type: ResourceType::Task,
                    command: Some(command.clone()),
                    ..Resource::default()
                };
                scripts.push(crate::core::codegen::apply_script(&task)?);
            }
            _ => {}
        }
    }
    Ok(scripts)
}

/// Scripts the container build runs. The image resource's own `packages` /
/// `command` only; unrelated resources in the config are NOT part of an image
/// build. Only an explicit `--sandbox` keeps the legacy behaviour of also
/// running every other (non-image) resource's apply script.
pub(crate) fn container_build_scripts(
    plan: &ImageBuildPlan,
    res: &Resource,
    config: &crate::core::types::ForjarConfig,
    explicit_sandbox: bool,
) -> Result<Vec<String>, String> {
    let mut scripts = image_build_scripts(plan, res)?;
    if !explicit_sandbox {
        return Ok(scripts);
    }
    scripts.extend(
        config
            .resources
            .values()
            .filter(|r| !matches!(r.resource_type, ResourceType::Image))
            .filter_map(|r| {
                let resolved = crate::core::resolver::resolve_resource_templates(
                    r,
                    &config.params,
                    &config.machines,
                )
                .ok()?;
                crate::core::codegen::apply_script(&resolved).ok()
            }),
    );
    Ok(scripts)
}

/// The plan reduced to its `path:` Files layers: what the container diff does
/// not carry and must be layered on top of it (IMG-001, forjar#757 review).
pub(crate) fn files_only_plan(plan: &ImageBuildPlan) -> ImageBuildPlan {
    let mut files = plan.clone();
    files
        .layers
        .retain(|l| matches!(l, LayerStrategy::Files { .. }));
    files
}
